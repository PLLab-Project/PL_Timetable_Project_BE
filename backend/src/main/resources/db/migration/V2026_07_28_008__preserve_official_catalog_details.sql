    'Ordered many-to-many rooms used by a normalized meeting. sessions.room_code remains the primary room for compatibility.';
COMMENT ON TABLE catalog_sources IS
    'Immutable provenance for an official catalog source file and parser run.';
COMMENT ON TABLE catalog_source_rows IS
    'Lossless source rows, including duplicate cross-listing rows, page locators, shading, and raw cells.';
COMMENT ON TABLE section_classification_contexts IS
    'Context-specific completion category and target grade for a section as printed under departments, programs, or liberal-education areas.';
